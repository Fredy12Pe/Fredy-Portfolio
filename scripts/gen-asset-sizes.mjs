// Regenerates app/projects/mood-tracker/assetSizes.ts from the exported Figma SVGs.
// Every layer must be drawn at the size Figma exported it at, otherwise the
// illustration stretches. Run with: node scripts/gen-asset-sizes.mjs
import fs from "node:fs";
import path from "node:path";

const dir = "public/projects/mood-tracker/assets";
const target = "app/projects/mood-tracker/assetSizes.ts";

const sizes = {};

for (const file of fs.readdirSync(dir).filter((f) => f.endsWith(".svg")).sort()) {
  const head = fs.readFileSync(path.join(dir, file), "utf8").slice(0, 600);
  const width = head.match(/\bwidth="([\d.]+)"/);
  const height = head.match(/\bheight="([\d.]+)"/);
  let size = width && height ? [Number(width[1]), Number(height[1])] : null;

  if (!size) {
    const viewBox = head.match(/viewBox="([-\d.eE]+)\s+([-\d.eE]+)\s+([\d.eE]+)\s+([\d.eE]+)"/);
    size = viewBox ? [Number(viewBox[3]), Number(viewBox[4])] : null;
  }

  if (!size) {
    throw new Error(`Could not determine intrinsic size for ${file}`);
  }

  sizes[file.replace(/\.svg$/, "")] = size;
}

const entries = Object.entries(sizes)
  .map(([name, [w, h]]) => `  ${JSON.stringify(name)}: [${w}, ${h}],`)
  .join("\n");

fs.writeFileSync(
  target,
  `/** Intrinsic size of every exported Figma asset, in Figma frame units. Generated by scripts/gen-asset-sizes.mjs. */\nexport const ASSET_SIZE: Record<string, readonly [number, number]> = {\n${entries}\n};\n`,
);

console.log(`wrote ${Object.keys(sizes).length} entries to ${target}`);
